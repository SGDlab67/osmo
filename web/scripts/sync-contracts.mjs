// Generates src/lib/contracts.ts from forge's build output (../out) and a deployments file
// (../deployments/<network>.json), and writes each contract's ABI back into that deployments
// file. Run it after `forge build` or a deploy:
//
//   npm run contracts                  # Monad testnet (deployments/monad-testnet.json)
//   NETWORK=local npm run contracts    # a local anvil deploy (deployments/local.json)
//   npm run contracts -- --check       # CI: fail if src/lib/contracts.ts is out of date
//
// The app never carries a hand-copied address or ABI, so a redeploy can't leave it pointing at
// old contracts.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const network = process.env.NETWORK ?? "monad-testnet";
const check = process.argv.includes("--check");
const target = join(here, "..", "src", "lib", "contracts.ts");
const deploymentsFile = join(root, "deployments", `${network}.json`);

const CONTRACTS = [
  ["Osmo", "osmoAbi"],
  ["UsernameRegistry", "usernameRegistryAbi"],
  ["Welcome", "welcomeAbi"],
  ["Charities", "charitiesAbi"],
  ["DemoAsset", "demoAssetAbi"],
];

function abiOf(name) {
  const f = join(root, "out", `${name}.sol`, `${name}.json`);
  if (!existsSync(f)) throw new Error(`${f} not found. Run \`forge build\` in the repo root first.`);
  return JSON.parse(readFileSync(f, "utf8")).abi;
}

const ZERO = "0x0000000000000000000000000000000000000000";
const d = JSON.parse(readFileSync(deploymentsFile, "utf8"));
const addr = (name) => d.contracts?.[name]?.address ?? ZERO;
const deployment = {
  network,
  chainId: d.chainId,
  rpc: d.rpc,
  explorer: d.explorer,
  deployBlock: d.contracts?.Osmo?.deployBlock ?? d.deployBlock ?? 0,
  osmo: addr("Osmo"),
  registry: addr("UsernameRegistry"),
  welcome: addr("Welcome"),
  charities: addr("Charities"),
};

const abis = Object.fromEntries(CONTRACTS.map(([name]) => [name, abiOf(name)]));
let out = `// Generated by \`npm run contracts\` from ../out and ../deployments/${network}.json. Do not edit by hand.\n\n`;
out += `export const deployment = ${JSON.stringify(deployment, null, 2)} as const;\n`;
for (const [name, id] of CONTRACTS) out += `\nexport const ${id} = ${JSON.stringify(abis[name], null, 2)} as const;\n`;

if (check) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.error("src/lib/contracts.ts is out of date. Run `forge build && npm run contracts` and commit the result.");
    process.exit(1);
  }
  console.log("src/lib/contracts.ts is up to date.");
} else {
  writeFileSync(target, out);
  // Keep the ABIs in the deployments file too, for anyone reading it without the app.
  for (const name of ["Osmo", "UsernameRegistry", "Welcome", "Charities"]) if (d.contracts?.[name]) d.contracts[name].abi = abis[name];
  writeFileSync(deploymentsFile, JSON.stringify(d, null, 2) + "\n");
  // The demo client (demo/index.html) loads its addresses from here.
  if (network === "monad-testnet") {
    const demo = { usernames: deployment.registry, osmo: deployment.osmo, share: d.demoAccounts?.share ?? d.contracts?.MockShare?.address ?? ZERO };
    writeFileSync(join(root, "demo", "deployment.js"), `// Generated by \`npm run contracts\` in web/. Do not edit by hand.\nwindow.DEPLOYMENT = ${JSON.stringify(demo, null, 2)};\n`);
  }
  console.log(`Wrote src/lib/contracts.ts for ${network}: Osmo ${deployment.osmo}, registry ${deployment.registry}, Welcome ${deployment.welcome}`);
}
